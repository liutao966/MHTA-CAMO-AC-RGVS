% =========================================================================
% main.m —— ICSSA 改进混沌麻雀搜索算法 三维路径规划入口（直接运行本文件即可）
% -------------------------------------------------------------------------
% 运行后依次弹出三组结果(每组 2 张图, 共 6 张):
%   1) 城市地图(city 平底+高楼)
%   2) 丘陵地图(hill 7 座高斯山体)
%   3) 山体+禁飞区+圆柱地图(legacy, 即 map.m 绘制的障碍物地图)
% 每组含: 三维地图+红色最优路径(绿色起点球/蓝色终点球)、ICSSA 收敛曲线。
% 三个地图规划完成后, 命令行会输出汇总表格, 展示每个地图的 6 个目标值:
%   路径长度 / 威胁代价 / 能耗 / 不平滑度 / 最小安全距离 / 飞行时间
%   以及综合成本(前4个目标加权求和, 算法实际优化的目标函数)。
%   飞行时间按 V=10 m/s 估算。
% =========================================================================
clear;
clc;
close all;

map_types = {'city', 'hill', 'legacy'};
nMaps = numel(map_types);
results = cell(1, nMaps);

for i = 1:nMaps
    fprintf('\n%%%%%%%%%%%%%%%%%%%% 地图 %d / %d %%%%%%%%%%%%%%%%%%%%\n', i, nMaps);
    results{i} = run_icssa(map_types{i});
end

%% 汇总输出三个地图的 6 个目标值 + 综合成本
fprintf('\n');
fprintf('====================================== 三地图规划结果汇总 ======================================\n');
fprintf('%-16s %10s %10s %10s %10s %12s %12s %12s\n', ...
    '地图', '综合成本', '长度(m)', '威胁', '能耗(Wh)', '不平滑度', '最小安全距', '飞行时间(s)');
fprintf('%s\n', repmat('-', 1, 16 + 10*7 + 1));
for i = 1:nMaps
    r = results{i};
    fprintf('%-16s %10.3f %10.2f %10.2f %10.2f %12.4f %12.2f %12.2f\n', ...
        r.map_name, r.best_cost, r.length, r.threat, r.energy, r.roughness, ...
        r.min_clearance, r.flight_time);
end
fprintf('==================================================================================================\n');
fprintf('注: 飞行时间 = 路径长度 / 飞行速度(V=10 m/s)\n');