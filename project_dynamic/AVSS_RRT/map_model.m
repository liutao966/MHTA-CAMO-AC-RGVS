function model = map_model()
% MAP_MODEL  返回与 map.m 一致的三维地形/障碍物模型
% -------------------------------------------------------------------------
% 该模型完全对应 map.m 中的场景，用于路径规划中的碰撞检测与地形查询：
%   1) 三座高斯山体（地形高度场）
%   2) 一个球形禁飞区
%   3) 九个圆柱体障碍物（带封顶，高 100）
% 返回的 model 结构体供 COA 算法（碰撞惩罚）与绘图函数共用。
% -------------------------------------------------------------------------

% ------- 地图边界 -------
model.map_min = [0,   0,   0];      % X/Y/Z 下界
model.map_max = [200, 200, 200];    % X/Y/Z 上界

% ------- 起点与终点 -------
model.start = [10,  10,  50];       % 绿色起点
model.goal  = [190, 190, 80];       % 蓝色终点

% ------- 三座高斯山体参数（与 map.m 完全一致）-------
% 每列: [中心x, 中心y, 幅值A, 宽度sigma]
model.mountains = [ 40, 140,  90, 30;
                   140,  40,  90, 30;
                   140, 140, 120, 30];

% ------- 球形禁飞区（与 map.m 完全一致）-------
model.ball.center = [100, 100, 0];  % 球心
model.ball.radius = 50;             % 半径

% ------- 圆柱体障碍物（与 map.m 完全一致）-------
model.cylinder.radius = 5;          % 半径
% 每行: [中心x, 中心y, 高度h]
model.cylinder.pos = [ 40,  70, 100;
                       70,  40, 100;
                       50,  50, 100;
                       90, 160, 100;
                      160,  80, 100;
                       80, 180, 100;
                      100, 180, 100;
                      180,  60, 100;
                      180, 100, 100];

% ------- 安全裕度（膨胀半径，让路径远离障碍物表面）-------
model.safe_margin = 2;
end
