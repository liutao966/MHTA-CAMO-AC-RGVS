function env = build_env()
%BUILD_ENV 构造统一的静态障碍环境（三座高斯山体 + 球形禁飞区 + 九根圆柱）。
% 三个算法共用同一确定性解析环境（地形无噪声），保证障碍数量梯度实验公平对比。
